-- Esquema inicial de la API de citas de la Clínica Salvador.

CREATE TABLE especialidad (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE medico (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres                VARCHAR(80)  NOT NULL,
    apellidos              VARCHAR(80)  NOT NULL,
    registro_profesional   VARCHAR(30)  NOT NULL UNIQUE,
    especialidad_id        BIGINT       NOT NULL REFERENCES especialidad (id),
    hora_inicio            TIME         NOT NULL,
    hora_fin               TIME         NOT NULL,
    activo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_medico_horario CHECK (hora_fin > hora_inicio)
);

CREATE TABLE paciente (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento    VARCHAR(2)   NOT NULL,
    documento         VARCHAR(20)  NOT NULL UNIQUE,
    nombres           VARCHAR(80)  NOT NULL,
    apellidos         VARCHAR(80)  NOT NULL,
    telefono          VARCHAR(20)  NOT NULL,
    correo            VARCHAR(120) NOT NULL,
    fecha_nacimiento  DATE         NOT NULL
);

CREATE TABLE cita (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id  BIGINT       NOT NULL REFERENCES paciente (id),
    medico_id    BIGINT       NOT NULL REFERENCES medico (id),
    fecha_hora   TIMESTAMP    NOT NULL,
    motivo       VARCHAR(255) NOT NULL,
    estado       VARCHAR(12)  NOT NULL,
    creada_en    TIMESTAMP    NOT NULL,
    CONSTRAINT ck_cita_estado CHECK (estado IN ('PROGRAMADA', 'ATENDIDA', 'CANCELADA'))
);

-- RN-01 y RN-02: un médico y un paciente no pueden tener dos citas activas a la misma hora.
-- Las citas canceladas no ocupan el horario, por eso los índices son parciales.
CREATE UNIQUE INDEX ux_cita_medico_horario
    ON cita (medico_id, fecha_hora) WHERE estado <> 'CANCELADA';

CREATE UNIQUE INDEX ux_cita_paciente_horario
    ON cita (paciente_id, fecha_hora) WHERE estado <> 'CANCELADA';

CREATE INDEX ix_cita_fecha ON cita (fecha_hora);
